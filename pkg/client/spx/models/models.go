// IntOrString represents a Kubernetes intstr value (number or string)
type IntOrString struct {
	IntVal int32
	StrVal string
	IsStr  bool
}

// UnmarshalJSON accepts a number or a string
func (v *IntOrString) UnmarshalJSON(data []byte) error {
	if len(data) > 0 && data[0] == '"' {
		v.IsStr = true
		return json.Unmarshal(data, &v.StrVal)
	}
	v.IsStr = false
	return json.Unmarshal(data, &v.IntVal)
}

// MarshalJSON serializes the value in its original form
func (v IntOrString) MarshalJSON() ([]byte, error) {
	if v.IsStr {
		return json.Marshal(v.StrVal)
	}
	return json.Marshal(v.IntVal)
}

// Int32 returns the numeric value (a numeric string is converted, otherwise 0)
func (v IntOrString) Int32() int32 {
	if !v.IsStr {
		return v.IntVal
	}
	n, err := strconv.ParseInt(v.StrVal, 10, 32)
	if err != nil {
		return 0
	}
	return int32(n)
}

