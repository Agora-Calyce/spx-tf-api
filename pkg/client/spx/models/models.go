// UnmarshalJSON accepte un nombre ou une chaîne
func (v *IntOrString) UnmarshalJSON(data []byte) error {
	if len(data) > 0 && data[0] == '"' {
		v.IsStr = true
		return json.Unmarshal(data, &v.StrVal)
	}
	v.IsStr = false
	return json.Unmarshal(data, &v.IntVal)
}

// MarshalJSON sérialise la valeur sous sa forme d'origine
func (v IntOrString) MarshalJSON() ([]byte, error) {
	if v.IsStr {
		return json.Marshal(v.StrVal)
	}
	return json.Marshal(v.IntVal)
}

// Int32 retourne la valeur numérique (une chaîne numérique est convertie, sinon 0)
func (v IntOrString) Int32() int32 {
	if !v.IsStr {
		return v.IntVal
	}
	n, err := strconv.ParseInt(v.StrVal, 10, 32)
	if err != nil {
		return 0
	}
	return int32(n)
}

// SPXSgPort représente un port de NetworkPolicy dans le format SPX (lecture)
type SPXSgPort struct {
	Port     *IntOrString `json:"port,omitempty"`
	EndPort  *int32       `json:"endPort,omitempty"`
	Protocol string       `json:"protocol,omitempty"`
}

// SPXPeer représente un pair dans le format SPX (lecture)
type SPXPeer struct {
	PodSelector SPXLabelSelector `json:"podSelector"`
	IPBlock     IPBlock          `json:"IPBlock"`
}

// SPXIngressRule représente une règle entrante dans le format SPX (lecture)
type SPXIngressRule struct {
	Ports    []SPXSgPort `json:"ports"`
	From     []SPXPeer   `json:"from"`
	AllowAll bool        `json:"allowAll"`
	DenyAll  bool        `json:"denyAll"`
}

// SPXEgressRule représente une règle sortante dans le format SPX (lecture)
type SPXEgressRule struct {
	Ports    []SPXSgPort `json:"ports"`
	To       []SPXPeer   `json:"to"`
	AllowAll bool        `json:"allowAll"`
	DenyAll  bool        `json:"denyAll"`
}

// SecurityGroupFullResponse représente la réponse complète pour un groupe de sécurité
type SecurityGroupFullResponse struct {
	ID            string                  `json:"id"`          // local ID
	EID           string                  `json:"eid"`         // effective ID
	ProductName   string                  `json:"productName"` // human-readable name
	CodeAZ        string                  `json:"codeAZ"`
	Gitops        string                  `json:"gitops"`
	ProductTypeID string                  `json:"productTypeId"`
	SecurityGroup SPXSecurityGroupDetails `json:"securityGroup"`
}

// SPXSecurityGroupDetails représente les détails internes d'un groupe de sécurité dans SPX
type SPXSecurityGroupDetails struct {
	Description string               `json:"description"`
	Spec        SPXSecurityGroupSpec `json:"spec"`
	SubnetEIds  []string             `json:"subnetEIds,omitempty"`
}

// SPXSecurityGroupSpec représente la spécification (NetworkPolicy) d'un groupe de sécurité dans SPX
type SPXSecurityGroupSpec struct {
	PolicyTypes []string         `json:"policyTypes"`
	PodSelector SPXLabelSelector `json:"podSelector"`
	Ingress     []SPXIngressRule `json:"ingress"`
	Egress      []SPXEgressRule  `json:"egress"`
}
