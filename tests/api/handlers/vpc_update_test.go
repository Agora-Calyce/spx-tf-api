const vpcWithRoutesJSON = `{
	"eid": "vpc-123",
	"productName": "%s",
	"vpc": {
		"spec": {
			"staticRoutes": [
				{"policy": "policyDst", "cidr": "192.168.10.0/24", "nextHopIP": "10.0.0.254", "routeTable": "subnet-1"},
				{"policy": "policyDst", "cidr": "0.0.0.0/0", "nextHopIP": "10.0.0.1", "routeTable": "subnet-1", "autoGenerated": true}
			]
		}
	}
}`

func runVPCUpdate(t *testing.T, serverURL string, body models.VPCRequest) *httptest.ResponseRecorder {
	t.Helper()
	e := echo.New()
	configStore := store.NewConfigStore()
	configStore.SetEndpoint(serverURL)
	h := handlers.NewVPCHandler(configStore)

	reqBody, _ := json.Marshal(body)
	req := httptest.NewRequest(http.MethodPut, "/orga-1/az1/proj-1/vpcs/vpc-123", bytes.NewBuffer(reqBody))
	req.Header.Set(echo.HeaderContentType, echo.MIMEApplicationJSON)
	req.Header.Set("Authorization", "api-token secret-token")
	rec := httptest.NewRecorder()
	c := e.NewContext(req, rec)
	c.SetParamNames("orga_id", "az", "project_id", "id")
	c.SetParamValues("orga-1", "az1", "proj-1", "vpc-123")

	assert.NoError(t, h.UpdateVPC(c))
	return rec
}

// Sans static_routes dans la requête, les routes utilisateur existantes doivent être renvoyées à SPX
// (l'API SPX remplace toutes les routes à chaque mise à jour) et les routes auto-générées ignorées.
func TestVPCHandler_UpdateVPC_PreservesStaticRoutes(t *testing.T) {
	callCount := 0
	var sentRoutes []map[string]interface{}
	mockServer := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		callCount++
		assert.Contains(t, r.URL.Path, "/vpc/vpc-123")
		switch callCount {
		case 1: // Get de l'état actuel
			assert.Equal(t, http.MethodGet, r.Method)
			w.Header().Set("Content-Type", "application/json")
			fmt.Fprintf(w, vpcWithRoutesJSON, "old-name")
		case 2: // Update
			assert.Equal(t, http.MethodPost, r.Method)
			raw, _ := io.ReadAll(r.Body)
			var body struct {
				General struct {
					ProductName string `json:"productName"`
				} `json:"general"`
				StaticRoutes []map[string]interface{} `json:"staticRoutes"`
			}
			assert.NoError(t, json.Unmarshal(raw, &body))
			assert.Equal(t, "new-name-req", body.General.ProductName)
			sentRoutes = body.StaticRoutes
			w.WriteHeader(http.StatusOK)
		case 3: // Get final
			assert.Equal(t, http.MethodGet, r.Method)
			w.Header().Set("Content-Type", "application/json")
			fmt.Fprintf(w, vpcWithRoutesJSON, "new-name-from-get")
		default:
			w.WriteHeader(http.StatusInternalServerError)
		}
	}))
	defer mockServer.Close()

	rec := runVPCUpdate(t, mockServer.URL, models.VPCRequest{Name: "new-name-req"})

	assert.Equal(t, http.StatusOK, rec.Code)
	assert.Equal(t, 3, callCount, "Get (état actuel), Update puis Get final")

	// Seule la route utilisateur est renvoyée, pas la route auto-générée de la NAT Gateway
	if assert.Len(t, sentRoutes, 1) {
		assert.Equal(t, "192.168.10.0/24", sentRoutes[0]["cidr"])
		assert.Equal(t, "subnet-1", sentRoutes[0]["routeTable"])
	}

	var resp models.VPC
	assert.NoError(t, json.Unmarshal(rec.Body.Bytes(), &resp))
	assert.Equal(t, "vpc-123", resp.ID)
	assert.Equal(t, "new-name-from-get", resp.Name, "Le nom doit provenir du Get final, pas de la requête")
	if assert.Len(t, resp.StaticRoutes, 1) {
		assert.Equal(t, models.StaticRoute{Policy: "policyDst", CIDR: "192.168.10.0/24", NextHopIP: "10.0.0.254", RouteTable: "subnet-1"}, resp.StaticRoutes[0])
	}
}

// Avec static_routes explicite, la liste est envoyée telle quelle (policy par défaut : policyDst)
func TestVPCHandler_UpdateVPC_ExplicitStaticRoutes(t *testing.T) {
	callCount := 0
	var sentRoutes []map[string]interface{}
	mockServer := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		callCount++
		switch callCount {
		case 1: // Update, sans Get préalable
			assert.Equal(t, http.MethodPost, r.Method)
			raw, _ := io.ReadAll(r.Body)
			var body struct {
				StaticRoutes []map[string]interface{} `json:"staticRoutes"`
			}
			assert.NoError(t, json.Unmarshal(raw, &body))
			sentRoutes = body.StaticRoutes
			w.WriteHeader(http.StatusOK)
		case 2:
			assert.Equal(t, http.MethodGet, r.Method)
			w.Header().Set("Content-Type", "application/json")
			fmt.Fprintf(w, vpcWithRoutesJSON, "vpc")
		default:
			w.WriteHeader(http.StatusInternalServerError)
		}
	}))
	defer mockServer.Close()

	routes := []models.StaticRoute{{CIDR: "172.16.0.0/16", NextHopIP: "10.0.0.10", RouteTable: "subnet-2"}}
	rec := runVPCUpdate(t, mockServer.URL, models.VPCRequest{Name: "vpc", StaticRoutes: &routes})

	assert.Equal(t, http.StatusOK, rec.Code)
	assert.Equal(t, 2, callCount)
	if assert.Len(t, sentRoutes, 1) {
		assert.Equal(t, "policyDst", sentRoutes[0]["policy"])
		assert.Equal(t, "172.16.0.0/16", sentRoutes[0]["cidr"])
		assert.Equal(t, "10.0.0.10", sentRoutes[0]["nextHopIP"])
		assert.Equal(t, "subnet-2", sentRoutes[0]["routeTable"])
	}
}

// Une liste vide explicite doit être envoyée comme [] (suppression de toutes les routes utilisateur)
func TestVPCHandler_UpdateVPC_EmptyStaticRoutes(t *testing.T) {
	var rawBody string
	mockServer := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Method == http.MethodPost {
			raw, _ := io.ReadAll(r.Body)
			rawBody = string(raw)
			w.WriteHeader(http.StatusOK)
			return
		}
		w.Header().Set("Content-Type", "application/json")
		fmt.Fprint(w, `{"eid": "vpc-123", "productName": "vpc"}`)
	}))
	defer mockServer.Close()

	empty := []models.StaticRoute{}
	rec := runVPCUpdate(t, mockServer.URL, models.VPCRequest{Name: "vpc", StaticRoutes: &empty})

	assert.Equal(t, http.StatusOK, rec.Code)
	assert.Contains(t, rawBody, `"staticRoutes":[]`)
}

func TestVPCRequest_Validate_StaticRoutes(t *testing.T) {
	bad := []models.StaticRoute{{CIDR: "10.0.0.0/8", RouteTable: "subnet-1", Policy: "invalid"}}
	assert.Error(t, (&models.VPCRequest{Name: "vpc", StaticRoutes: &bad}).Validate())

	noTable := []models.StaticRoute{{CIDR: "10.0.0.0/8"}}
	assert.Error(t, (&models.VPCRequest{Name: "vpc", StaticRoutes: &noTable}).Validate())

	ok := []models.StaticRoute{{CIDR: "10.0.0.0/8", RouteTable: "subnet-1", Policy: "policySrc"}}
	assert.NoError(t, (&models.VPCRequest{Name: "vpc", StaticRoutes: &ok}).Validate())
}
